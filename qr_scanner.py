import streamlit as st
import cv2
import numpy as np

from database import get_connection


def qr_scanner_page(user):

    # -----------------------------------------
    # HEALTHCARE UI STYLING
    # -----------------------------------------

    st.markdown("""
    <style>
    .qr-header {
        background: linear-gradient(120deg, #087f8c, #13a89e);
        padding: 25px;
        border-radius: 16px;
        color: white;
        margin-bottom: 22px;
    }

    .qr-header h2 {
        color: white;
        margin: 0;
        font-size: 27px;
    }

    .qr-header p {
        color: #e7ffff;
        margin-top: 8px;
    }

    .section-heading {
        font-size: 20px;
        font-weight: 700;
        margin-top: 15px;
        margin-bottom: 12px;
    }

    .qr-detail-card {
        background: var(--secondary-background-color);
        border: 1px solid rgba(128,128,128,0.2);
        border-left: 4px solid #0d9488;
        padding: 15px;
        border-radius: 12px;
        margin-bottom: 12px;
    }

    div[data-testid="stMetric"] {
        background: var(--secondary-background-color);
        border: 1px solid rgba(128,128,128,0.2);
        border-radius: 12px;
        padding: 15px;
    }

    div[data-testid="stAlert"] {
        border-radius: 10px;
    }

    div.stButton > button {
        border-radius: 9px;
        font-weight: 600;
        min-height: 42px;
    }
    </style>
    """, unsafe_allow_html=True)

    # -----------------------------------------
    # HEADER
    # -----------------------------------------

    st.markdown("""
    <div class="qr-header">
        <h2>📱 QR Code Scanner</h2>
        <p>Scan biomedical waste QR codes and retrieve
        verified waste record information.</p>
    </div>
    """, unsafe_allow_html=True)

    st.info(
        "Upload a QR code generated by MED WASTE AI "
        "to retrieve its associated waste record."
    )

    # -----------------------------------------
    # QR IMAGE UPLOAD
    # -----------------------------------------

    st.markdown(
        '<div class="section-heading">📤 Upload QR Code</div>',
        unsafe_allow_html=True
    )

    uploaded_qr = st.file_uploader(
        "Choose QR Code Image",
        type=["png", "jpg", "jpeg"],
        help="Upload a clear image of a MED WASTE AI QR code.",
        key="qr_image_upload"
    )

    if uploaded_qr is None:

        st.markdown("""
        <div class="qr-detail-card">
            <h4>How to scan a QR code</h4>
            <p>1. Open your generated waste QR code.</p>
            <p>2. Upload the QR image using the upload option.</p>
            <p>3. The system reads the QR token.</p>
            <p>4. The matching waste record is displayed.</p>
        </div>
        """, unsafe_allow_html=True)

        st.caption("MED WASTE AI | QR Scanner")
        return

    # -----------------------------------------
    # DISPLAY UPLOADED IMAGE
    # -----------------------------------------

    st.markdown("#### Uploaded QR Image")

    st.image(
        uploaded_qr,
        caption="Uploaded QR Code",
        width=250
    )

    # -----------------------------------------
    # READ IMAGE
    # -----------------------------------------

    image_bytes = np.frombuffer(
        uploaded_qr.getvalue(),
        np.uint8
    )

    image = cv2.imdecode(
        image_bytes,
        cv2.IMREAD_COLOR
    )

    if image is None:
        st.error("Unable to read this image. Please upload another image.")
        return

    # -----------------------------------------
    # DECODE QR CODE
    # -----------------------------------------

    with st.spinner("Scanning QR code..."):

        detector = cv2.QRCodeDetector()

        qr_token, points, _ = detector.detectAndDecode(image)

    if not qr_token:
        st.error(
            "No valid QR code detected. "
            "Please upload a clear QR code image."
        )
        return

    st.success("QR code scanned successfully!")

    # -----------------------------------------
    # FIND MATCHING WASTE RECORD
    # -----------------------------------------

    conn = get_connection()

    try:

        record = conn.execute(
            """
            SELECT
                w.*,
                h.hospital_name,
                q.qr_code_path
            FROM qr_records q
            JOIN waste_records w
                ON q.waste_id = w.waste_id
            LEFT JOIN hospitals h
                ON w.hospital_id = h.hospital_id
            WHERE q.qr_token = ?
            """,
            (qr_token,)
        ).fetchone()

    finally:
        conn.close()

    if record is None:

        st.error(
            "No matching waste record found for this QR code."
        )

        return

    # -----------------------------------------
    # HOSPITAL ACCESS VALIDATION
    # -----------------------------------------

    if (
        user["role"] != "admin"
        and record["hospital_id"] != user["hospital_id"]
    ):

        st.error(
            "Access denied! You do not have permission "
            "to view this hospital's waste record."
        )

        return

    # -----------------------------------------
    # WASTE RECORD DETAILS
    # -----------------------------------------

    st.divider()

    st.markdown(
        '<div class="section-heading">📋 Waste Record Details</div>',
        unsafe_allow_html=True
    )

    # Main metrics
    col1, col2, col3 = st.columns(3)

    col1.metric(
        "Waste ID",
        f"#{record['waste_id']}"
    )

    col2.metric(
        "Waste Weight",
        f"{record['waste_weight']} kg"
    )

    col3.metric(
        "Colour Category",
        record["colour_category"] or "Not available"
    )

    st.divider()

    # Hospital information
    st.markdown("#### 🏥 Hospital Information")

    col1, col2 = st.columns(2)

    with col1:
        st.write("**Hospital Name**")
        st.write(record["hospital_name"] or "Not available")

        st.write("**Facility Type**")
        st.write(record["facility_type"] or "Not available")

    with col2:
        st.write("**Facility Name**")
        st.write(record["facility_name"] or "Not available")

        st.write("**Facility Location**")
        st.write(record["facility_location"] or "Not available")

    st.divider()

    # Waste information
    st.markdown("#### ♻️ Waste Information")

    st.write("**Waste Materials**")

    st.info(
        record["waste_materials"] or "No waste material details available."
    )

    st.divider()

    # Verification and collection information
    st.markdown("#### 📊 Record Status")

    col1, col2 = st.columns(2)

    with col1:
        st.write("**Verification Status**")

        verification_status = (
            record["verification_status"] or "Pending"
        )

        if verification_status == "Approved":
            st.success(verification_status)

        elif verification_status == "Rejected":
            st.error(verification_status)

        else:
            st.warning(verification_status)

    with col2:
        st.write("**Collection Status**")

        collection_status = (
            record["collection_status"] or "Not Available"
        )

        if collection_status == "Completed":
            st.success(collection_status)

        elif collection_status == "In Transit":
            st.info(collection_status)

        else:
            st.warning(collection_status)

    # -----------------------------------------
    # FINAL SUCCESS
    # -----------------------------------------

    st.divider()

    st.success(
        "Waste record retrieved successfully!"
    )

    st.caption(
        "MED WASTE AI | Smart Biomedical Waste Management System"
    )